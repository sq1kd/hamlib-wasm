/**
 * Emit every generated artifact from the classified model.
 *
 * The generator owns these files, all derived from the allowlist and the
 * compiler AST:
 *
 *   native/generated/results.inc       C++ value objects for generated results
 *   native/generated/operations.inc    generated Facade method bodies
 *   native/generated/capabilities.inc  the rig_caps capability matrix
 *   native/generated/embind.inc        Embind registrations (hand + generated)
 *   src/native/generated/operations.ts the strict low-level + generic contract
 *
 * Nothing here is written by hand, and nothing here is written per operation by
 * hand either: a new upstream release rebuilds the same files from the new
 * headers, so a version bump cannot silently drift.
 *
 * Authored as TypeScript and run directly by Node's type stripping, so this
 * file must stay erasable (no enums, namespaces or parameter properties).
 */
import { pascalCase, type GeneratedOperation } from './classify.ts';
import type { Model, ModelOperation } from './config.ts';
import type { ProjectionSpec, TypeBinding } from './types.ts';

const CONFIG_PATH = 'packages/hamlib-wasm/hamlib.config.yaml';

const GENERATED_HEADER =
  `/* Generated by packages/hamlib-codegen from ${CONFIG_PATH} and the upstream AST. */`;

const CONTRACT_HEADER = `// Generated by packages/hamlib-codegen from ${CONFIG_PATH} and the upstream AST.
// Do not edit: run \`mise run generate\` after changing the config.`;

/** The fixed single-output result value objects every generated getter shares. */
const FLAT_RESULTS: Readonly<Record<string, readonly (readonly [string, string])[]>> = {
  NumberResult: [['code', 'int'], ['value', 'double'], ['error', 'string']],
  TextResult: [['code', 'int'], ['value', 'string'], ['error', 'string']],
  BoolResult: [['code', 'int'], ['value', 'bool'], ['error', 'string']],
};

const CPP_ARGUMENT: Readonly<Record<string, string>> = {
  int: 'int',
  double: 'double',
  bool: 'bool',
  string: 'const std::string &',
};

const TS_ARGUMENT: Readonly<Record<string, string>> = {
  int: 'number',
  double: 'number',
  bool: 'boolean',
  string: 'string',
};

function structSpec(binding: TypeBinding): ProjectionSpec {
  if (!binding.projection) {
    throw new Error('struct binding is missing its projection');
  }

  return binding.projection;
}

/** One flattened field of a getter's result. */
interface FlatField {
  readonly name: string;
  readonly binding: TypeBinding;
  /** Index of the getter output this field came from. */
  readonly out: number;
  /** The C struct member, or `null` when the output is a scalar. */
  readonly member: string | null;
  /** Length of a `char[N]` member, or `null`. */
  readonly charArray: number | null;
}

/**
 * Flatten a getter's outputs into result fields.  A struct output is expanded
 * into one field per projected member so the result stays a flat value object
 * (Embind does not nest value objects reliably); a single scalar keeps the
 * shared `value` field.
 */
function flatGetterFields(operation: GeneratedOperation): FlatField[] {
  const flat: FlatField[] = [];

  for (const [index, output] of operation.outputs.entries()) {
    if (output.binding.category === 'struct') {
      for (const field of structSpec(output.binding).fields) {
        flat.push({
          name: field.name,
          binding: field.binding,
          out: index,
          member: field.member,
          charArray: field.charArray,
        });
      }
    } else {
      flat.push({
        name: operation.outputs.length === 1 ? 'value' : output.field,
        binding: output.binding,
        out: index,
        member: null,
        charArray: null,
      });
    }
  }

  return flat;
}

/** The projections a getter/setter/pure operation needs a C++ type for. */
export function usedProjections(operations: readonly GeneratedOperation[]): ProjectionSpec[] {
  const specs = new Map<string, ProjectionSpec>();

  for (const operation of operations) {
    for (const argument of operation.arguments) {
      if (argument.binding.category === 'struct') {
        const spec = structSpec(argument.binding);
        specs.set(spec.cpp, spec);
      }
    }

    if (operation.pure?.category === 'struct') {
      const spec = structSpec(operation.pure);
      specs.set(spec.cpp, spec);
    }
  }

  return [...specs.values()].sort((a, b) => a.cpp.localeCompare(b.cpp));
}

function projectionFieldCpp(binding: TypeBinding): string {
  switch (binding.boundary) {
    case 'bool':
      return 'bool';
    case 'string':
      return 'std::string';
    case 'int':
      return 'int';
    default:
      return 'double';
  }
}
/** Convert a C struct member into a projection field. */
function assignProjectionField(
  field: { readonly name: string; readonly binding: TypeBinding; readonly charArray: number | null },
  source: string,
  destination: string,
  index: number,
): string[] {
  switch (field.binding.category) {
    case 'enum': {
      const text = `projected${index}`;
      return [
        `        const char *${text} = ${field.binding.enumStr}(${source});`,
        `        ${destination} = ${text} ? ${text} : "";`,
      ];
    }
    case 'string':
      /* A `char[N]` member is a non-null array; a `char *` member may be null. */
      return field.charArray !== null
        ? [`        ${destination} = std::string(${source});`]
        : [`        ${destination} = ${source} ? std::string(${source}) : std::string();`];
    case 'boolean':
      return [`        ${destination} = ${source};`];
    default:
      return [`        ${destination} = (double) ${source};`];
  }
}

interface ResultSpec {
  readonly name: string;
  readonly fields: readonly (readonly [string, string])[];
}

function fieldsForSpec(fields: readonly (readonly [string, string])[]): readonly (readonly [string, string])[] {
  return fields;
}

/** The generated value objects actually referenced by the operations. */
export function resultSpecs(operations: readonly GeneratedOperation[]): ResultSpec[] {
  const specs = new Map<string, ResultSpec>();

  for (const operation of operations) {
    if (operation.shape !== 'get') {
      continue;
    }

    if (operation.outputs.length === 1 && operation.outputs[0]?.binding.category !== 'struct') {
      specs.set(operation.result, { name: operation.result, fields: FLAT_RESULTS[operation.result] ?? [] });
      continue;
    }

    const fields: (readonly [string, string])[] = [['code', 'int']];

    for (const field of flatGetterFields(operation)) {
      fields.push([field.name, field.binding.boundary]);
    }

    fields.push(['error', 'string']);
    specs.set(operation.result, { name: operation.result, fields: fieldsForSpec(fields) });
  }

  return [...specs.values()].sort((a, b) => a.name.localeCompare(b.name));
}

export function emitResults(operations: readonly GeneratedOperation[]): string {
  const lines = [GENERATED_HEADER, ''];

  for (const spec of usedProjections(operations)) {
    lines.push(`struct ${spec.cpp}`);
    lines.push('{');

    for (const field of spec.fields) {
      lines.push(`    ${projectionFieldCpp(field.binding)} ${field.name};`);
    }

    lines.push('};');
    lines.push('');
  }

  for (const spec of resultSpecs(operations)) {
    lines.push(`struct ${spec.name}`);
    lines.push('{');

    for (const [field, type] of spec.fields) {
      lines.push(type === 'string' ? `    std::string ${field};` : `    ${type} ${field};`);
    }

    lines.push('};');
    lines.push('');
  }

  return `${lines.join('\n')}\n`;
}

function localName(index: number): string {
  return `arg${index}`;
}

/** Native local holding the converted value; distinct from the parameter name. */
function valueName(index: number): string {
  return `value${index}`;
}

/** Native local holding a getter output. */
function outName(index: number): string {
  return `out${index}`;
}

/** The local of the `setting_t` argument a `value_t` is interpreted against. */
function settingLocalName(operation: GeneratedOperation): string | null {
  const index = operation.arguments.findIndex(
    (argument) => argument.binding.native === 'setting_t',
  );

  return index >= 0 ? valueName(index) : null;
}

/** The C++ parameter list of a generated operation's JavaScript arguments. */
function parameterDeclarations(operation: GeneratedOperation): string[] {
  return operation.arguments.map((argument, index) => {
    if (argument.binding.category === 'struct') {
      return `const ${structSpec(argument.binding).cpp} & ${localName(index)}`;
    }

    const type = argument.binding.boundary === 'string'
      ? CPP_ARGUMENT.string
      : CPP_ARGUMENT[argument.binding.boundary];

    return `${type} ${localName(index)}`;
  });
}

/**
 * Declare and convert every JavaScript argument into the native local the call
 * needs (enum parse, `value_t` union, `const char *`, or a cast).
 */
function emitArgumentLocals(operation: GeneratedOperation, failureType: string): string[] {
  const lines: string[] = [];
  const setting = settingLocalName(operation);

  for (const [index, argument] of operation.arguments.entries()) {
    const parameter = localName(index);
    const local = valueName(index);
    const binding = argument.binding;

    if (binding.category === 'struct') {
      lines.push(`        ${binding.native} ${local}{};`);

      for (const field of structSpec(binding).fields) {
        const source = `${parameter}.${field.name}`;
        const target = `${local}.${field.member}`;

        if (field.charArray !== null) {
          lines.push(`        std::strncpy(${target}, ${source}.c_str(), sizeof(${target}) - 1);`);
        } else if (field.binding.category === 'enum') {
          lines.push(`        ${target} = ${field.binding.enumParse}(${source}.c_str());`);
        } else if (field.binding.category === 'string') {
          lines.push(`        ${target} = ${source}.c_str();`);
        } else if (field.binding.category === 'boolean') {
          lines.push(`        ${target} = ${source};`);
        } else {
          lines.push(`        ${target} = (${field.binding.native}) ${source};`);
        }
      }

      lines.push('');
      continue;
    }

    if (binding.category === 'enum') {
      lines.push(`        ${binding.native} ${local} = ${binding.enumParse}(${parameter}.c_str());`);
      lines.push('');
      lines.push(`        if (${local} == ${binding.enumNone}) { return failure<${failureType}>(-RIG_EINVAL); }`);
      lines.push('');
      continue;
    }

    if (binding.valueAccess) {
      lines.push(`        value_t ${local}{};`);
      lines.push(`        ${local}.${binding.valueAccess} = (${binding.valueAccess === 'f' ? 'float' : 'int'}) ${parameter};`);
      continue;
    }

    if (binding.valuePredicate && setting) {
      lines.push(`        value_t ${local}{};`);
      lines.push(
        `        if (${binding.valuePredicate}(${setting})) { ${local}.f = (float) ${parameter}; } `
        + `else { ${local}.i = (int) ${parameter}; }`,
      );
      continue;
    }

    if (binding.category === 'string') {
      lines.push(`        const char *${local} = ${parameter}.c_str();`);
      continue;
    }

    lines.push(`        ${binding.native} ${local} = static_cast<${binding.native}>(${parameter});`);
  }

  return lines;
}

/** The C++ expression that packs a mapped value into a result field. */
function packValue(binding: TypeBinding, source: string, field: string): string[] {
  switch (binding.category) {
    case 'enum':
      return [
        `        const char *${field}_text = ${binding.enumStr}(${source});`,
        `        result.${field} = ${field}_text ? ${field}_text : "";`,
      ];
    case 'string':
      return [`        result.${field} = ${source} ? std::string(${source}) : std::string();`];
    case 'boolean':
      return [`        result.${field} = ${source};`];
    default:
      return [`        result.${field} = (double) ${source};`];
  }
}

/** The C++ expression that returns a mapped value from a pure function. */
function pureReturn(binding: TypeBinding, call: string): string[] {
  if (binding.valueAccess) {
    return [
      `        value_t result = ${call};`,
      `        return (double) result.${binding.valueAccess};`,
    ];
  }

  switch (binding.category) {
    case 'enum':
      return [
        `        const auto ${'result'} = ${call};`,
        `        const char *text = ${binding.enumStr}(${'result'});`,
        '        return text ? std::string(text) : std::string();',
      ];
    case 'string':
      return [
        `        const char *text = ${call};`,
        '        return text ? std::string(text) : std::string();',
      ];
    case 'boolean':
      return [`        return ${call};`];
    default:
      return [`        return (double) ${call};`];
  }
}

/** The result binding of a pure operation; classification guarantees it exists. */
function pureBinding(operation: GeneratedOperation): TypeBinding {
  if (!operation.pure) {
    throw new Error(`pure operation ${operation.symbol} has no result binding`);
  }

  return operation.pure;
}

function callArguments(operation: GeneratedOperation): string[] {
  let out = 0;

  return operation.plan.map((entry) => {
    switch (entry.kind) {
      case 'rig':
        return 'rig';
      case 'target-vfo':
        return 'RIG_VFO_CURR';
      case 'out': {
        const name = outName(out);
        out++;
        return `&${name}`;
      }
      case 'value': {
        const argument = operation.arguments[entry.argument];

        /* Hamlib passes every struct by pointer, so a built struct local is
         * handed over by address. */
        return argument?.binding.category === 'struct'
          ? `&${valueName(entry.argument)}`
          : valueName(entry.argument);
      }
      default:
        throw new Error(`unreachable plan for ${operation.symbol}`);
    }
  });
}

function emitGetter(operation: GeneratedOperation): string[] {
  const lines: string[] = [];
  const parameters = ['int handle', ...parameterDeclarations(operation)];
  const setting = settingLocalName(operation);

  lines.push(`    ${operation.result} ${operation.method}(${parameters.join(', ')})`);
  lines.push('    {');
  lines.push('        webserial_clear_error();');
  lines.push('');
  lines.push('        RIG *rig = lookupRig(handle);');
  lines.push('');
  lines.push(`        if (!rig) { return failure<${operation.result}>(-RIG_EINVAL); }`);
  lines.push('');
  lines.push(...emitArgumentLocals(operation, operation.result));

  for (const [index, output] of operation.outputs.entries()) {
    lines.push(`        ${output.binding.native} ${outName(index)}{};`);
  }

  lines.push('');
  lines.push(`        int rc = ${operation.symbol}(${callArguments(operation).join(', ')});`);
  lines.push('');
  lines.push(`        if (rc != RIG_OK) { return failure<${operation.result}>(rc); }`);
  lines.push('');
  lines.push(`        ${operation.result} result;`);
  lines.push('        result.code = RIG_OK;');

  for (const flat of flatGetterFields(operation)) {
    const source = flat.member ? `${outName(flat.out)}.${flat.member}` : outName(flat.out);

    if (flat.binding.valueAccess) {
      lines.push(`        result.${flat.name} = (double) ${source}.${flat.binding.valueAccess};`);
      continue;
    }

    if (flat.binding.valuePredicate && setting) {
      lines.push(
        `        result.${flat.name} = ${flat.binding.valuePredicate}(${setting}) `
        + `? (double) ${source}.f : (double) ${source}.i;`,
      );
      continue;
    }

    /* A projected `char[N]` member is a non-null array, so guard only a
     * nullable `char *` member. */
    if (flat.member !== null && flat.binding.category === 'string') {
      lines.push(
        flat.charArray !== null
          ? `        result.${flat.name} = std::string(${source});`
          : `        result.${flat.name} = ${source} ? std::string(${source}) : std::string();`,
      );
      continue;
    }

    lines.push(...packValue(flat.binding, source, flat.name));
  }

  lines.push('        return result;');
  lines.push('    }');

  return lines;
}

function emitSetter(operation: GeneratedOperation): string[] {
  const lines: string[] = [];
  const parameters = parameterDeclarations(operation);

  lines.push(`    CodeResult ${operation.method}(int handle, ${parameters.join(', ')})`);
  lines.push('    {');
  lines.push('        webserial_clear_error();');
  lines.push('');
  lines.push('        RIG *rig = lookupRig(handle);');
  lines.push('');
  lines.push('        if (!rig) { return failure<CodeResult>(-RIG_EINVAL); }');
  lines.push('');
  lines.push(...emitArgumentLocals(operation, 'CodeResult'));

  lines.push(`        int rc = ${operation.symbol}(${callArguments(operation).join(', ')});`);
  lines.push('');
  lines.push('        if (rc != RIG_OK) { return failure<CodeResult>(rc); }');
  lines.push('');
  lines.push('        CodeResult result;');
  lines.push('        result.code = RIG_OK;');
  lines.push('        return result;');
  lines.push('    }');

  return lines;
}

function emitPure(operation: GeneratedOperation): string[] {
  const binding = pureBinding(operation);
  const lines: string[] = [];
  const needsHandle = operation.plan.some((entry) => entry.kind === 'rig');
  const boundary = binding.category === 'struct'
    ? structSpec(binding).cpp
    : (binding.boundary === 'string' ? 'std::string' : binding.boundary);
  const parameters = parameterDeclarations(operation);

  lines.push(`    ${boundary} ${operation.method}(${[needsHandle ? 'int handle' : null, ...parameters].filter((entry) => entry !== null).join(', ')})`);
  lines.push('    {');

  if (needsHandle) {
    lines.push('        RIG *rig = lookupRig(handle);');
    lines.push('');
    lines.push(`        if (!rig) { return ${binding.boundary === 'string' ? 'std::string()' : '{}'}; }`);
    lines.push('');
  }

  for (const [index, argument] of operation.arguments.entries()) {
    const parameter = localName(index);
    const local = valueName(index);
    const argBinding = argument.binding;

    if (argBinding.category === 'enum') {
      lines.push(`        ${argBinding.native} ${local} = ${argBinding.enumParse}(${parameter}.c_str());`);
      continue;
    }

    if (argBinding.category === 'string') {
      lines.push(`        const char *${local} = ${parameter}.c_str();`);
      continue;
    }

    lines.push(`        ${argBinding.native} ${local} = static_cast<${argBinding.native}>(${parameter});`);
  }

  lines.push('');
  const call = `${operation.symbol}(${callArguments(operation).join(', ')})`;

  if (binding.category === 'struct') {
    const spec = structSpec(binding);
    lines.push(`        const ${binding.native} *source = ${call};`);
    lines.push(`        ${spec.cpp} result{};`);
    lines.push('        if (!source) { return result; }');

    spec.fields.forEach((field, index) => {
      lines.push(...assignProjectionField(field, `source->${field.member}`, `result.${field.name}`, index));
    });

    lines.push('        return result;');
  } else {
    lines.push(...pureReturn(binding, call));
  }

  lines.push('    }');

  return lines;
}

export function emitOperations(operations: readonly GeneratedOperation[]): string {
  const lines: string[] = [GENERATED_HEADER, ''];

  for (const operation of operations) {
    if (operation.shape === 'get') {
      lines.push(...emitGetter(operation));
    } else if (operation.shape === 'set') {
      lines.push(...emitSetter(operation));
    } else {
      lines.push(...emitPure(operation));
    }

    lines.push('');
  }

  return `${lines.join('\n')}\n`;
}

/** The `rig_caps` member a get/set operation is gated on, or `null`. */
export function capabilityMember(operation: GeneratedOperation): string | null {
  if (operation.shape === 'pure') {
    return null;
  }

  return operation.symbol.startsWith('rig_') ? operation.symbol.slice(4) : operation.symbol;
}

export function emitCapabilities(
  operations: readonly GeneratedOperation[],
  capsMembers: ReadonlySet<string>,
): string {
  const lines: string[] = [GENERATED_HEADER, ''];
  const gated = operations.filter((operation) => {
    const member = capabilityMember(operation);
    return member !== null && capsMembers.has(member);
  });
  const ungated = operations.filter((operation) => {
    const member = capabilityMember(operation);
    return member === null || !capsMembers.has(member);
  });

  lines.push('    std::vector<std::string> capabilities(int modelId)');
  lines.push('    {');
  lines.push('        std::vector<std::string> available;');
  lines.push('        const struct rig_caps *caps = rig_get_caps((rig_model_t) modelId);');
  lines.push('');
  lines.push('        if (!caps) { return available; }');
  lines.push('');

  for (const operation of gated) {
    lines.push(`        if (caps->${capabilityMember(operation)} != NULL) { available.push_back("${operation.method}"); }`);
  }

  for (const operation of ungated) {
    lines.push(`        available.push_back("${operation.method}");`);
  }

  lines.push('');
  lines.push('        return available;');
  lines.push('    }');

  return `${lines.join('\n')}\n`;
}

function emitValueObject(
  cppType: string,
  binding: string,
  fields: readonly (readonly [string, string])[],
): string[] {
  const lines = [`    emscripten::value_object<${cppType}>("${binding}")`];

  for (const [field] of fields) {
    lines.push(`    .field("${field}", &${cppType}::${field})`);
  }

  lines[lines.length - 1] += ';';
  return lines;
}

export function emitEmbind(
  model: Model,
  operations: readonly GeneratedOperation[],
): string {
  const lines: string[] = [GENERATED_HEADER];

  for (const [name, result] of Object.entries(model.results)) {
    lines.push('');
    lines.push(...emitValueObject(name, result.binding ?? name, result.fields));
  }

  for (const spec of resultSpecs(operations)) {
    lines.push('');
    lines.push(...emitValueObject(spec.name, spec.name, spec.fields));
  }

  for (const spec of usedProjections(operations)) {
    lines.push('');
    lines.push(
      ...emitValueObject(
        spec.cpp,
        spec.cpp,
        spec.fields.map((field) => [field.name, field.binding.boundary] as const),
      ),
    );
  }

  for (const vector of model.vectors) {
    lines.push('');
    lines.push(`    emscripten::register_vector<${vector.type}>("${vector.binding}");`);
  }

  lines.push('');
  lines.push('    emscripten::register_vector<std::string>("StringList");');

  lines.push('');
  lines.push('    emscripten::function("capabilities", +[](int modelId)');
  lines.push('    {');
  lines.push('        return facade().capabilities(modelId);');
  lines.push('    });');

  for (const operation of model.operations) {
    const parameters = operation.args.map(
      ([name, type]) => `${CPP_ARGUMENT[type] ?? 'int'} ${name}`,
    );
    const call = `facade().${operation.name}(${operation.args.map(([name]) => name).join(', ')})`;

    lines.push('');
    lines.push(`    emscripten::function("${operation.name}", +[](${parameters.join(', ')})`);
    lines.push('    {');
    lines.push(`        return ${call};`);
    lines.push('    });');
  }

  for (const operation of operations) {
    lines.push('');
    lines.push(...emitEmbindFunction(operation));
  }

  return `${lines.join('\n')}\n`;
}

/** The Embind argument count of a generated operation (handle included). */
export function embindArity(operation: GeneratedOperation): number {
  const needsHandle = operation.shape !== 'pure' || operation.plan.some((entry) => entry.kind === 'rig');
  return (needsHandle ? 1 : 0) + operation.arguments.length;
}

function emitEmbindFunction(operation: GeneratedOperation): string[] {
  const lines: string[] = [];
  const needsHandle = operation.shape !== 'pure' || operation.plan.some((entry) => entry.kind === 'rig');
  const parameters = operation.arguments.map((argument, index) => {
    if (argument.binding.category === 'struct') {
      return `const ${structSpec(argument.binding).cpp} & ${localName(index)}`;
    }

    const type = argument.binding.boundary === 'string'
      ? CPP_ARGUMENT.string
      : CPP_ARGUMENT[argument.binding.boundary];

    return `${type} ${localName(index)}`;
  });
  const allParameters = [...(needsHandle ? ['int handle'] : []), ...parameters];
  const call = `facade().${operation.method}(${[
    ...(needsHandle ? ['handle'] : []),
    ...operation.arguments.map((_, index) => localName(index)),
  ].join(', ')})`;

  lines.push(`    emscripten::function("${operation.method}", +[](${allParameters.join(', ')})`);
  lines.push('    {');
  lines.push(`        return ${call};`);
  lines.push('    });');

  return lines;
}

/** The shared single-output results that every generated getter may use. */
const SHARED_RESULTS: ReadonlySet<string> = new Set(Object.keys(FLAT_RESULTS));

function vectorBindingFor(model: Model, type: string): string | null {
  return model.vectors.find((vector) => vector.type === type)?.binding ?? null;
}

function manualResultType(model: Model, result: string): string {
  if (result === 'string') {
    return 'string';
  }

  if (result.endsWith('[]')) {
    /* `ModelInfo[]` and the projected-struct lists resolve through the
     * registered vector binding, so a hand-written operation can return any
     * declared `std::vector<T>`. */
    return vectorBindingFor(model, result.slice(0, -2)) ?? 'RigModelList';
  }

  return result;
}

