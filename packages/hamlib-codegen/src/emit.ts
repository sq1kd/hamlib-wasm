const METHOD_HEADER = GENERATED_HEADER;

/** Types that need no import in a method signature. */
const PRIMITIVE_TS: ReadonlySet<string> = new Set(['number', 'string', 'boolean', 'void']);

/**
 * Family order also fixes the class inheritance chain: each file extends the
 * one before it, so a family can be read (and reviewed on an upstream bump) on
 * its own without a hundred unrelated methods in the diff.
 */
const METHOD_CHAIN: readonly string[] = [
  'codec',
  'ext',
  'settings',
  'memory',
  'vfo',
  'control',
  'info',
  'misc',
];

const FAMILY_RULES: readonly (readonly [string, RegExp])[] = [
  ['codec', /^rig_(str|parse)/],
  ['ext', /^rig_(ext_|get_ext_|set_ext_|token_foreach|confparam_lookup|token_lookup)/],
  ['settings', /(level|func|parm)$|agc/],
  ['memory', /(mem|channel|bank)/],
  ['vfo', /(vfo|split|rit|xit|rptr|scan|trn|twiddle|uplink)/],
  ['control', /(freq|mode|ptt|ant|dcd|powerstat|reset|clock|ctcss|dcs|tone)/],
  ['info', /(info|copyright|license|version|resolution|passband|is_model|setting2idx|idx2setting|count|lookup)/],
];

/** The generated file a symbol's method is emitted into. */
export function familyOf(operation: GeneratedOperation): string {
  for (const [family, pattern] of FAMILY_RULES) {
    if (pattern.test(operation.symbol)) {
      return family;
    }
  }

  return 'misc';
}

function classNameFor(family: string): string {
  return `${pascalCase(family)}Methods`;
}

function methodNeedsHandle(operation: GeneratedOperation): boolean {
  return operation.shape !== 'pure' || operation.plan.some((entry) => entry.kind === 'rig');
}

function methodIsGated(operation: GeneratedOperation, capsMembers: ReadonlySet<string>): boolean {
  if (operation.shape === 'pure') {
    return false;
  }

  const member = capabilityMember(operation);

  return member !== null && capsMembers.has(member);
}

/** Non-primitive types a family's method signatures name. */
function signatureImports(operations: readonly GeneratedOperation[]): string[] {
  const names = new Set<string>();

  for (const operation of operations) {
    for (const argument of operation.arguments) {
      if (!PRIMITIVE_TS.has(argument.binding.ts)) {
        names.add(argument.binding.ts);
      }
    }

    if (operation.shape === 'pure' && operation.pure && !PRIMITIVE_TS.has(operation.pure.ts)) {
      if (!structProjection(operation)) {
        names.add(operation.pure.ts);
      }
    }
  }

  return [...names].sort();
}

const PRIMITIVE_GETTER = (operation: GeneratedOperation): boolean =>
  operation.shape === 'get'
  && operation.outputs.length === 1
  && operation.outputs[0]?.binding.category !== 'struct';

/** One concrete method body; every shape runs inside `serialized`. */
function methodLines(
  operation: GeneratedOperation,
  capsMembers: ReadonlySet<string>,
): string[] {
  const names = parameterNames(
    operation.arguments.length,
    operation.arguments.map((argument) => argument.field),
  );
  const parameters = operation.arguments
    .map((argument, index) => `${names[index]}: ${argument.binding.ts}`)
    .join(', ');
  const args = [
    ...(methodNeedsHandle(operation) ? ['this.handle()'] : []),
    ...names,
  ].join(', ');
  const call = `this.native().${operation.method}(${args})`;
  const lines = [`  async ${operation.method}(${parameters}): Promise<${publicResultType(operation)}> {`];

  if (methodIsGated(operation, capsMembers)) {
    lines.push(`    this.available('${operation.method}');`);
  }

  if (operation.shape === 'pure') {
    const projected = structProjection(operation);

    /* A "pure" helper still enters the Wasm module, so it must take the queue
     * slot: calling it while another native call is suspended would re-enter
     * the unwound Asyncify stack.  Inside a compound the scope runs this
     * directly, because the body already owns the slot. */
    lines.push(`    return this.serialized('${operation.method}', async () => {`);
    lines.push(projected
      ? `      return ${projected.project}(await ${call});`
      : `      return ${call};`);
    lines.push('    });');
    lines.push('  }');
    return lines;
  }

  lines.push(`    return this.serialized('${operation.method}', async () => {`);
  lines.push(`      const result = await ${call};`);
  lines.push(`      if (result.code !== 0) { throw this.failed(result, '${operation.method}'); }`);

  if (operation.shape === 'get') {
    if (PRIMITIVE_GETTER(operation)) {
      /* A value-object string field is typed `EmbindString` by the emitted
       * declaration; the public contract is `string`. */
      const unbox = operation.outputs[0]?.binding.ts === 'string'
        ? 'String(result.value)'
        : 'result.value';
      lines.push(`      return ${unbox};`);
    } else {
      const fields = flatGetterFields(operation)
        .map((field) => {
          const value = `result.${field.name}`;
          const boxed = field.binding.ts === 'string' ? `String(${value})` : value;

          return `${field.name}: ${boxed}`;
        })
        .join(', ');
      lines.push(`      return { ${fields} };`);
    }
  }

  lines.push('    });');
  lines.push('  }');

  return lines;
}

function baseFile(): string {
  return `${METHOD_HEADER}

import type { NativeOperations } from '../operations.js';

/** The low-level call result: a Hamlib code plus the transport error text. */
export interface GeneratedCallResult {
  readonly code: number;
  readonly error: unknown;
}

/**
 * Shared plumbing for the generated rig methods.  \`src/hamlib.ts\` supplies the
 * implementation: the native module, the current handle, the single call queue,
 * the capability gate and the error conversion.
 */
export abstract class GeneratedRigBase {
  protected abstract native(): NativeOperations;

  protected abstract handle(): number;

  protected abstract serialized<T>(
    operation: string,
    work: () => Promise<T>,
  ): Promise<T>;

  protected abstract available(operation: string): void;

  protected abstract failed(result: GeneratedCallResult, operation: string): Error;
}
`;
}

function familyFile(
  family: string,
  className: string,
  previousClass: string,
  previousPath: string,
  operations: readonly GeneratedOperation[],
  capsMembers: ReadonlySet<string>,
): string {
  const imports = signatureImports(operations);
  const projectionValues = new Set<string>();
  const projectionTypes = new Set<string>();

  for (const operation of operations) {
    const projected = structProjection(operation);

    if (projected) {
      projectionValues.add(`import { ${projected.project} } from '${projected.methodImport}';`);
      projectionTypes.add(`import type { ${projected.element} } from '${projected.methodImport}';`);
    }
  }

  const lines = [METHOD_HEADER, ''];

  for (const name of imports) {
    lines.push(`import type { ${name} } from '../../hamlib-wasm.mjs';`);
  }

  for (const statement of projectionValues) {
    lines.push(statement);
  }

  for (const statement of projectionTypes) {
    lines.push(statement);
  }

  if (imports.length > 0 || projectionValues.size > 0 || projectionTypes.size > 0) {
    lines.push('');
  }

  lines.push(`import { ${previousClass} } from '${previousPath}';`);
  lines.push('');
  lines.push(`/** Generated operations in the ${family} family. */`);
  lines.push(`export abstract class ${className} extends ${previousClass} {`);

  for (const operation of operations) {
    lines.push('');
    lines.push(...methodLines(operation, capsMembers));
  }

  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

function indexFile(className: string, path: string): string {
  return `${METHOD_HEADER}

import type { GeneratedPublicOperations } from '../operations.js';
import { ${className} } from '${path}';

/**
 * Every generated operation as a real, typed method, assembled from the family
 * classes.  \`RigHandle\` extends this; \`tsc\` proves the methods satisfy
 * \`GeneratedPublicOperations\`.
 */
export abstract class GeneratedRigMethods
  extends ${className}
  implements GeneratedPublicOperations {}
`;
}

/**
 * The generated method files, keyed by their path relative to
 * \`src/native/generated/methods\`.
 */
export function emitMethodFiles(
  model: Model,
  operations: readonly GeneratedOperation[],
  capsMembers: ReadonlySet<string>,
): readonly (readonly [string, string])[] {
  const grouped = new Map<string, GeneratedOperation[]>();

  for (const operation of operations) {
    const family = familyOf(operation);
    const list = grouped.get(family) ?? [];
    list.push(operation);
    grouped.set(family, list);
  }

  const present = METHOD_CHAIN.filter((family) => grouped.has(family));
  const bespoke = bespokeOperations(model);
  const files: (readonly [string, string])[] = [['base.ts', baseFile()]];
  let previousClass = 'GeneratedRigBase';
  let previousPath = './base.js';

  /* Bespoke methods sit at the head of the chain: their bodies are the only
   * ones the generator cannot write from the AST, so they read first. */
  if (bespoke.length > 0) {
    files.push(['bespoke.ts', bespokeFile(model, bespoke)]);
    previousClass = 'BespokeMethods';
    previousPath = './bespoke.js';
  }

  for (const family of present) {
    const className = classNameFor(family);
    files.push([
      `${family}.ts`,
      familyFile(family, className, previousClass, previousPath, grouped.get(family) as GeneratedOperation[], capsMembers),
    ]);
    previousClass = className;
    previousPath = `./${family}.js`;
  }

  files.push(['index.ts', indexFile(previousClass, previousPath)]);

  return files;
}
