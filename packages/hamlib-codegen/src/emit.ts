/**
 * The projection a pure helper's `struct` result crosses through.
 *
 * `rig_ext_lookup`/`rig_ext_lookup_tok` return a `struct confparams *`, which
 * the Embind declaration types as `RigConfparams` with `EmbindString` fields.
 * `src/native/confparams.ts` owns the narrowed public shape, so the emitted
 * method projects through it instead of handing the raw value object to a
 * caller.
 */
const STRUCT_RESULTS: Readonly<Record<string, {
  readonly element: string;
  readonly project: string;
  /** Import path from `src/native/generated`. */
  readonly contractImport: string;
  /** Import path from `src/native/generated/methods`. */
  readonly methodImport: string;
}>> = {
  RigConfparams: {
    element: 'RigConfparam',
    project: 'projectConfparam',
    contractImport: '../confparams.js',
    methodImport: '../../confparams.js',
  },
};

/** The projection a pure operation's struct result crosses through, if any. */
function structProjection(operation: GeneratedOperation): (typeof STRUCT_RESULTS)[string] | undefined {
  const binding = operation.pure;

  return binding?.category === 'struct' ? STRUCT_RESULTS[binding.ts] : undefined;
}

/**
 * The projection a bespoke vector result crosses through.
 *
 * `tokenForeach` and the three `ext*Foreach` walkers return
 * `std::vector<RigConfparams>`; the element type is the same projected
 * `struct confparams` the lookups return, so it drains through the module that
 * owns the narrowed public shape, one `projectConfparam` per entry, and the
 * native vector is freed.  A second such result should grow an entry here
 * rather than a second special case in the emitters.
 */
const VECTOR_RESULTS: Readonly<Record<string, {
  readonly element: string;
  readonly collect: string;
  /** Import path from `src/native/generated`. */
  readonly contractImport: string;
  /** Import path from `src/native/generated/methods`. */
  readonly methodImport: string;
}>> = {
  'RigConfparams[]': {
    element: 'RigConfparam',
    collect: 'collectConfparams',
    contractImport: '../confparams.js',
    methodImport: '../../confparams.js',
  },
};

/** The rig-scoped operations the config declares; each becomes a real method. */
export function bespokeOperations(model: Model): readonly ModelOperation[] {
  return model.operations.filter((operation) => operation.scope === 'rig');
}

/** The field carrying the value, when the result has exactly one besides the code. */
function bespokeValue(model: Model, operation: ModelOperation): readonly [string, string] | null {
  if (operation.result.endsWith('[]')) {
    return null;
  }

  const fields = model.results[operation.result]?.fields ?? FLAT_RESULTS[operation.result] ?? [];

  for (const field of fields) {
    if (field[0] !== 'code' && field[0] !== 'error') {
      return field;
    }
  }

  return null;
}

/** The TypeScript type a bespoke operation's method resolves to. */
export function bespokeResultType(model: Model, operation: ModelOperation): string {
  if (operation.result.endsWith('[]')) {
    return `${VECTOR_RESULTS[operation.result]?.element ?? 'unknown'}[]`;
  }

  const value = bespokeValue(model, operation);

  return value === null ? 'void' : (TS_ARGUMENT[value[1]] ?? 'number');
}

/**
 * The public shape of a bespoke operation: its declared native arguments minus
 * the handle, which the connected rig supplies.
 */
function bespokeParameters(operation: ModelOperation): { readonly parameters: string; readonly call: string } {
  const [, ...rest] = operation.args;
  const names = parameterNames(rest.length, rest.map(([name]) => name));

  return {
    parameters: rest
      .map(([, type], index) => `${names[index]}: ${TS_ARGUMENT[type] ?? 'number'}`)
      .join(', '),
    call: `this.native().${operation.name}(${['this.handle()', ...names].join(', ')})`,
  };
}

/**
 * One bespoke method body.  The shape follows the declared result, so a config
 * entry needs no hand-written TypeScript: a code-only result returns `void`, a
 * single-value result unwraps its field, a vector result is collected into a
 * plain array and the native vector is freed.
 */
function bespokeMethodLines(model: Model, operation: ModelOperation): string[] {
  const { parameters, call } = bespokeParameters(operation);
  const lines = [
    `  async ${operation.name}(${parameters}): Promise<${bespokeResultType(model, operation)}> {`,
  ];

  if (operation.capability !== undefined) {
    lines.push(`    this.available('${operation.name}');`);
  }

  if (operation.result.endsWith('[]')) {
    lines.push(`    return this.serialized('${operation.name}', async () =>`);
    lines.push(`      ${VECTOR_RESULTS[operation.result]?.collect ?? 'void'}(await ${call}));`);
    lines.push('  }');

    return lines;
  }

  lines.push(`    return this.serialized('${operation.name}', async () => {`);
  lines.push(`      const result = await ${call};`);
  lines.push(`      if (result.code !== 0) { throw this.failed(result, '${operation.name}'); }`);

  const value = bespokeValue(model, operation);

  if (value !== null) {
    const access = `result.${value[0]}`;

    lines.push(`      return ${value[1] === 'string' ? `String(${access})` : access};`);
  }

  lines.push('    });');
  lines.push('  }');

  return lines;
}

function bespokeFile(model: Model, operations: readonly ModelOperation[]): string {
  const lines = [METHOD_HEADER, ''];
  const valueImports = new Set<string>();
  const typeImports = new Set<string>();

  for (const operation of operations) {
    const vector = operation.result.endsWith('[]')
      ? VECTOR_RESULTS[operation.result]
      : undefined;

    if (vector) {
      valueImports.add(`import { ${vector.collect} } from '${vector.methodImport}';`);
      typeImports.add(`import type { ${vector.element} } from '${vector.methodImport}';`);
    }
  }

  for (const statement of valueImports) {
    lines.push(statement);
  }

  for (const statement of typeImports) {
    lines.push(statement);
  }

  if (valueImports.size > 0 || typeImports.size > 0) {
    lines.push('');
  }

  lines.push("import { GeneratedRigBase } from './base.js';");
  lines.push('');
  lines.push('/**');
  lines.push(' * Operations whose C++ body is hand-written in `native/facade.cpp`:');
  lines.push(' * buffers a signature cannot describe, the table walkers, extended');
  lines.push(' * settings and PTT.');
  lines.push(' * The method itself is generated from the config like every other.');
  lines.push(' */');
  lines.push('export abstract class BespokeMethods extends GeneratedRigBase {');

  for (const operation of operations) {
    lines.push('');
    lines.push(...bespokeMethodLines(model, operation));
  }

  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

/** The TypeScript type a generated operation's result unwraps to. */
function publicResultType(operation: GeneratedOperation): string {
  if (operation.shape === 'set') {
    return 'void';
  }

  if (operation.shape === 'pure') {
    const projected = structProjection(operation);

    return projected?.element ?? (operation.pure as TypeBinding).ts;
  }

  if (operation.outputs.length === 1 && operation.outputs[0]?.binding.category !== 'struct') {
    const [only] = operation.outputs;

    if (only) {
      return only.binding.ts;
    }
  }

  const fields = flatGetterFields(operation)
    .map((field) => `${field.name}: ${field.binding.ts}`)
    .join('; ');

  return `{ ${fields} }`;
}

/** Distinct, valid parameter names for the ergonomic interface. */
function parameterNames(count: number, proposed: readonly string[]): string[] {
  const used = new Set<string>();

  return Array.from({ length: count }, (_, index) => {
    const base = /^[A-Za-z_][A-Za-z0-9_]*$/.test(proposed[index] ?? '')
      ? (proposed[index] as string)
      : `arg${index}`;
    let name = base;
    let suffix = 1;

    while (used.has(name)) {
      name = `${base}${suffix++}`;
    }

    used.add(name);
    return name;
  });
}

export function emitContract(
  model: Model,
  operations: readonly GeneratedOperation[],
): string {
  const imported = new Set<string>(['MainModule', 'RigModelList', 'StringList']);

  for (const operation of model.operations) {
    const type = manualResultType(model, operation.result);

    if (type in model.results || SHARED_RESULTS.has(type)) {
      imported.add(type);
    }
  }

  for (const vector of model.vectors) {
    imported.add(vector.binding);
  }

  for (const spec of resultSpecs(operations)) {
    imported.add(spec.name);
  }

  for (const spec of usedProjections(operations)) {
    imported.add(spec.cpp);
  }

  const lines: string[] = [CONTRACT_HEADER, ''];
  const bespoke = bespokeOperations(model);
  const projectionImports = new Set<string>();

  for (const operation of operations) {
    const projected = structProjection(operation);

    if (projected) {
      projectionImports.add(`import type { ${projected.element} } from '${projected.contractImport}';`);
    }
  }

  /* A bespoke operation's vector result is declared as an array of the same
   * projected element type, so the contract names it too. */
  for (const operation of bespoke) {
    const vector = operation.result.endsWith('[]')
      ? VECTOR_RESULTS[operation.result]
      : undefined;

    if (vector) {
      projectionImports.add(`import type { ${vector.element} } from '${vector.contractImport}';`);
    }
  }

  for (const name of [...imported].sort()) {
    lines.push(`import type { ${name} } from '../hamlib-wasm.mjs';`);
  }

  for (const statement of projectionImports) {
    lines.push(statement);
  }

  lines.push('');
  lines.push('/**');
  lines.push(' * A native call may suspend the C stack (Emscripten Asyncify).');
  lines.push(' * When it does, the Embind function returns a promise instead of a value,');
  lines.push(' * so every transport operation is typed as `T | Promise<T>`.');
  lines.push(' */');
  lines.push('export type Asyncify<T> = T | Promise<T>;');
  lines.push('');
  lines.push('/**');
  lines.push(' * The low-level operation surface of the Wasm module, derived from the');
  lines.push(' * allowlist and the upstream AST rather than from the emitted declaration.');
  lines.push(' *');
  lines.push(' * `src/hamlib.ts` asserts that the built module satisfies this contract, so a');
  lines.push(' * binding that drifts from the allowlist fails the typecheck.');
  lines.push(' */');
  lines.push('export interface NativeOperations {');

  for (const operation of model.operations) {
    const parameters = operation.args.map(
      ([name, type]) => `${name}: ${TS_ARGUMENT[type] ?? 'number'}`,
    );

    lines.push('  /** Bound to the bespoke facade body in native/facade.cpp. */');
    lines.push(
      `  ${operation.name}(${parameters.join(', ')}): Asyncify<${manualResultType(model, operation.result)}>;`,
    );
  }

  for (const operation of operations) {
    const needsHandle = operation.shape !== 'pure' || operation.plan.some((entry) => entry.kind === 'rig');
    const parameters = [
      ...(needsHandle ? ['handle: number'] : []),
      ...operation.arguments.map((argument) => `${argument.name}: ${argument.binding.ts}`),
    ];
    const resultType = operation.shape === 'pure'
      ? pureBinding(operation).ts
      : manualResultType(model, operation.result);

    lines.push(`  /** ${operation.shape === 'pure' ? 'Pure computation: no transport access.' : 'Can suspend: the result is a promise when the transport has to wait.'} */`);
    lines.push(
      `  ${operation.method}(${parameters.join(', ')}): Asyncify<${resultType}>;`,
    );
  }

  lines.push('');
  lines.push('  /**');
  lines.push('   * The generated-op names a rig model supports, from `struct rig_caps`.');
  lines.push('   * Pure computation, so the result is never a promise.');
  lines.push('   */');
  lines.push('  capabilities(modelId: number): StringList;');
  lines.push('}');
  lines.push('');
  lines.push('/**');
  lines.push(' * Compile-time proof that the module Emscripten emitted still matches the');
  lines.push(' * allowlist.  The generator guarantees every operation is present, so this');
  lines.push(' * only has to keep the two views in step.');
  lines.push(' */');
  lines.push(
    'export type NativeContractCheck = Expect<MainModule extends NativeOperations ? true : false>;',
  );
  lines.push('');
  lines.push('type Expect<T extends true> = T;');
  lines.push('');
  lines.push('/**');
  lines.push(' * A boolean capability flag on the catalogue entry (`RigModel`), for the');
  lines.push(' * operations the `rig_caps` matrix cannot describe: a backend that drives');
  lines.push(' * push-to-talk over the serial RTS/DTR line declares no `get_ptt`/`set_ptt`');
  lines.push(' * function pointer, yet PTT works through the port.');
  lines.push(' */');
  lines.push(
    `export type RigFlag = ${(model.results.ModelInfo?.fields ?? [])
      .map(([name]) => name)
      .filter((name) => name.startsWith('can'))
      .map((name) => `'${name}'`)
      .join(' | ')};`,
  );
  lines.push('');
  lines.push('/**');
  lines.push(' * Operations gated on one of those flags, so `src/hamlib.ts` can fold them');
  lines.push(' * into the capability list it builds for a model.');
  lines.push(' */');
  lines.push('export const FLAG_GATED_OPERATIONS: readonly (readonly [string, RigFlag])[] = [');
  for (const operation of bespoke) {
    if (operation.capability !== undefined) {
      lines.push(`  ['${operation.name}', '${operation.capability}'],`);
    }
  }
  lines.push('];');
  lines.push('');
  lines.push('/**');
  lines.push(' * Every generated operation as a method.  `GeneratedRigMethods`');
  lines.push(' * (`methods/index.ts`) implements it with a real method per operation, and');
  lines.push(' * `src/hamlib.ts` extends that class, so a new operation is callable without');
  lines.push(' * any hand-written method and without a string-keyed dispatcher.');
  lines.push(' */');
  lines.push('export interface GeneratedPublicOperations {');

  for (const operation of operations) {
    const names = parameterNames(
      operation.arguments.length,
      operation.arguments.map((argument) => argument.field),
    );
    const parameters = operation.arguments.map(
      (argument, index) => `${names[index]}: ${argument.binding.ts}`,
    );

    lines.push(`  ${operation.method}(${parameters.join(', ')}): Promise<${publicResultType(operation)}>;`);
  }

  for (const operation of bespoke) {
    lines.push(
      `  ${operation.name}(${bespokeParameters(operation).parameters}): `
      + `Promise<${bespokeResultType(model, operation)}>;`,
    );
  }

  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

