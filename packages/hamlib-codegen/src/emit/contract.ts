/**
 * `src/native/generated/operations.ts`: the low-level contract the built
 * module must satisfy, the capability flags, and the public operation
 * interface with Hamlib's own documentation.
 *
 * Authored as TypeScript and run directly by Node's type stripping, so this
 * file must stay erasable (no enums, namespaces or parameter properties).
 */
import type { Model, ModelOperation } from '../config.ts';
import { commentBlock, renderDoc, type DocTarget, type DocumentedValue, type UpstreamDoc } from '../docs.ts';
import {
  bespokeOperations,
  CONFIG_PATH,
  Imports,
  tsArgument,
  vectorBinding,
  type OperationFacts,
} from './common.ts';
import { bespokeParameters, bespokeSignature, generatedSignature, pairType } from './surface.ts';

const CONTRACT_HEADER = `// SPDX-License-Identifier: MIT AND LGPL-2.1-or-later
// Generated by packages/hamlib-codegen from ${CONFIG_PATH} and the upstream AST.
// The method documentation is Hamlib's own (LGPL-2.1-or-later), taken from the
// pinned release; the code is MIT.
// Do not edit: run \`mise run generate\` after changing the config.`;

/** Upstream documentation for the contract, and the C parameter names it is keyed by. */
export interface ContractDocs {
  readonly upstream: ReadonlyMap<string, UpstreamDoc>;
  /** The C parameter names of an upstream function, in declaration order. */
  readonly parameters: (symbol: string) => readonly string[];
}

/** The TypeScript result of a bespoke native call: a scalar, a vector or a value object. */
function nativeResultType(model: Model, result: string, imports: Imports): string {
  if (result === 'string' || result === 'int' || result === 'double' || result === 'bool') {
    return tsArgument(result);
  }

  return imports.type('embind', result.endsWith('[]') ? vectorBinding(model, result) : result);
}

/** What a generated method takes and returns, in upstream parameter names. */
function generatedDocTarget(facts: OperationFacts, parameters: readonly string[]): DocTarget {
  const { operation } = facts;
  const cName = (index: number): string => parameters[index] ?? '';
  const outputs = operation.outputs.map((output) => ({
    c: cName(output.parameter),
    js: output.field,
    binding: output.binding,
  }));

  /* The fields seeding one struct are documented once, as their object. */
  const documented = operation.arguments.flatMap((argument, index): DocumentedValue[] => {
    const parameter = facts.parameters[index];

    if (parameter?.object === undefined) {
      return [{ c: cName(argument.parameter), js: parameter?.name ?? '', binding: argument.binding }];
    }

    const members = new Map(operation.arguments.flatMap((other) =>
      (other.parameter === argument.parameter && other.member ? [[other.member.name, other.field] as const] : [])));

    return operation.arguments.findIndex((other) => other.parameter === argument.parameter) === index
      ? [{ c: cName(argument.parameter), js: parameter.object, binding: null, members }]
      : [];
  });

  return {
    symbol: operation.symbol,
    arguments: documented,
    result: operation.shape === 'set'
      ? { kind: 'void' }
      : operation.shape === 'pure'
        ? { kind: 'value', value: { c: '', js: '', binding: operation.pure } }
        : outputs.length === 1 || operation.outputs.some((output) => output.binding.category === 'struct')
          ? { kind: 'value', value: outputs[0] ?? null }
          : { kind: 'object', fields: outputs },
  };
}

/**
 * The upstream call a bespoke operation documents itself with: its single
 * call, unless the operation reshapes it (a table walker returns an array
 * where upstream takes a callback, so the upstream text would mislead).
 */
function bespokeDocTarget(
  operation: ModelOperation,
  returnsValue: boolean,
  parameters: (symbol: string) => readonly string[],
): DocTarget | null {
  const [symbol, ...others] = operation.calls;

  if (symbol === undefined || others.length > 0 || symbol.endsWith('_foreach')) {
    return null;
  }

  /* Bespoke arguments follow the C parameters once the handle and the target
   * VFO the facade supplies are skipped; an output comes after them. */
  const values = parameters(symbol).filter((name) => name !== 'rig' && name !== 'vfo');
  const args = bespokeParameters(operation);

  return {
    symbol,
    arguments: args.map(([name], index) => ({ c: values[index] ?? '', js: name, binding: null })),
    result: returnsValue
      ? { kind: 'value', value: { c: values[args.length] ?? '', js: '', binding: null } }
      : { kind: 'void' },
  };
}

export function emitContract(model: Model, facts: readonly OperationFacts[], docs?: ContractDocs): string {
  const imports = new Imports();
  const bespoke = bespokeOperations(model);
  const body: string[] = [];

  imports.type('embind', 'MainModule');
  body.push('/**');
  body.push(' * A native call may suspend the C stack (Emscripten Asyncify).');
  body.push(' * When it does, the Embind function returns a promise instead of a value,');
  body.push(' * so every transport operation is typed as `T | Promise<T>`.');
  body.push(' */');
  body.push('export type Asyncify<T> = T | Promise<T>;');
  body.push('');
  body.push('/**');
  body.push(' * The low-level operation surface of the Wasm module, derived from the');
  body.push(' * config and the upstream AST rather than from the emitted declaration.');
  body.push(' *');
  body.push(' * `src/raw.ts` asserts that the built module satisfies this contract, so a');
  body.push(' * binding that drifts from the generator fails the typecheck.');
  body.push(' */');
  body.push('export interface NativeOperations {');

  for (const operation of model.operations) {
    const parameters = operation.args.map((pair) => `${pair[0]}: ${pairType(pair, imports)}`);

    body.push('  /** Bound to the bespoke facade body in native/facade.cpp. */');
    body.push(`  ${operation.name}(${parameters.join(', ')}): Asyncify<${nativeResultType(model, operation.result, imports)}>;`);
  }

  for (const fact of facts) {
    const parameters = [
      ...(fact.needsHandle ? ['handle: number'] : []),
      ...fact.parameters.map((parameter) => `${parameter.local}: ${imports.ts(parameter.binding)}`),
    ];

    body.push(`  /** ${fact.operation.shape === 'pure' ? 'Pure computation: no transport access.' : 'Can suspend: the result is a promise when the transport has to wait.'} */`);
    body.push(`  ${fact.operation.method}(${parameters.join(', ')}): Asyncify<${imports.type('embind', fact.result)}>;`);
  }

  body.push('');
  body.push('  /**');
  body.push('   * The generated-op names a rig model supports, from `struct rig_caps`.');
  body.push('   * Pure computation, so the result is never a promise.');
  body.push('   */');
  body.push(`  capabilities(modelId: number): ${imports.type('embind', 'StringList')};`);
  body.push('}');
  body.push('');
  body.push('/**');
  body.push(' * Compile-time proof that the module Emscripten emitted still matches the');
  body.push(' * generated surface.  The generator guarantees every operation is present, so this');
  body.push(' * only has to keep the two views in step.');
  body.push(' */');
  body.push('export type NativeContractCheck = Expect<MainModule extends NativeOperations ? true : false>;');
  body.push('');
  body.push('type Expect<T extends true> = T;');
  body.push('');
  body.push('/**');
  body.push(' * A boolean capability flag on the catalogue entry (`RigModel`), for the');
  body.push(' * operations the `rig_caps` matrix cannot describe: a backend that drives');
  body.push(' * push-to-talk over the serial RTS/DTR line declares no `get_ptt`/`set_ptt`');
  body.push(' * function pointer, yet PTT works through the port.');
  body.push(' */');
  body.push(`export type RigFlag = ${model.flags.map((name) => `'${name}'`).join(' | ')};`);
  body.push('');
  body.push('/**');
  body.push(' * Operations gated on one of those flags, so `src/raw.ts` can fold them');
  body.push(' * into the capability list it builds for a model.');
  body.push(' */');
  body.push('export const FLAG_GATED_OPERATIONS: readonly (readonly [string, RigFlag])[] = [');

  for (const operation of model.operations) {
    if (operation.capability !== undefined) {
      body.push(`  ['${operation.name}', '${operation.capability}'],`);
    }
  }

  body.push('];');
  body.push('');
  body.push('/**');
  body.push(' * Every generated operation as a method.  `GeneratedRigMethods`');
  body.push(' * (`methods/index.ts`) implements it with a real method per operation, and');
  body.push(' * `src/raw.ts` extends that class, so a new operation is callable without');
  body.push(' * any hand-written method and without a string-keyed dispatcher.');
  body.push(' */');
  body.push('export interface GeneratedPublicOperations {');

  /* Upstream cross-references link to the method that binds the call. */
  const methods = new Map<string, string>([
    ...facts.map((fact) => [fact.operation.symbol, fact.operation.method] as const),
    ...bespoke.flatMap((operation) =>
      operation.calls.length === 1 ? [[operation.calls[0] as string, operation.name] as const] : []),
  ]);

  for (const fact of facts) {
    const signature = generatedSignature(fact, imports);
    const doc = docs === undefined
      ? null
      : renderDoc(
        docs.upstream.get(fact.operation.symbol),
        generatedDocTarget(fact, docs.parameters(fact.operation.symbol)),
        methods,
      );

    if (doc !== null) {
      body.push(...commentBlock(doc, '  '));
    }

    body.push(`  ${fact.operation.method}(${signature.parameters}): Promise<${signature.result}>;`);
  }

  for (const operation of bespoke) {
    const signature = bespokeSignature(model, operation, imports);
    const target = docs === undefined ? null : bespokeDocTarget(operation, signature.result !== 'void', docs.parameters);
    const doc = docs === undefined || target === null
      ? null
      : renderDoc(docs.upstream.get(target.symbol), target, methods);

    if (doc !== null) {
      body.push(...commentBlock(doc, '  '));
    }

    body.push(`  ${operation.name}(${signature.parameters}): Promise<${signature.result}>;`);
  }

  body.push('}');
  body.push('');

  return [
    CONTRACT_HEADER,
    '',
    ...imports.render({ embind: '../hamlib-wasm.mjs', names: './names.js', confparams: '../confparams.js' }),
    '',
    ...body,
  ].join('\n');
}
