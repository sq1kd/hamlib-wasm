/**
 * What every emitter shares: the per-operation facts, the result value
 * objects, the projections, the boundary type tables and the import
 * collector.  Each fact about an operation - whether it takes the rig
 * handle, which value object it returns, which fields that carries, which
 * `rig_caps` member gates it - is decided here once and read by the C++, the
 * contract and the method emitters alike.
 *
 * Authored as TypeScript and run directly by Node's type stripping, so this
 * file must stay erasable (no enums, namespaces or parameter properties).
 */
import type { GeneratedOperation } from '../classify.ts';
import type { ConfigPair, Model, ModelOperation } from '../config.ts';
import { VOCABULARY_TYPES } from '../enums.ts';
import type { BoundaryType, ProjectionSpec, TypeBinding } from '../types.ts';

export const CONFIG_PATH = 'packages/hamlib-wasm/hamlib.config.yaml';

export const GENERATED_HEADER =
  '/* SPDX-License-Identifier: MIT */\n'
  + `/* Generated by packages/hamlib-codegen from ${CONFIG_PATH} and the upstream AST. */`;

/** One field of a value object that crosses the Embind boundary. */
export interface ValueObjectField {
  readonly name: string;
  readonly boundary: string;
}

export interface ValueObject {
  readonly name: string;
  readonly fields: readonly ValueObjectField[];
}

function valueObject(name: string, fields: readonly (readonly [string, BoundaryType])[]): ValueObject {
  return { name, fields: fields.map(([field, boundary]) => ({ name: field, boundary })) };
}

/** The single-value results generated operations share with the bespoke ones. */
const FLAT_RESULTS: readonly ValueObject[] = [
  valueObject('NumberResult', [['code', 'int'], ['value', 'double'], ['error', 'string']]),
  valueObject('TextResult', [['code', 'int'], ['value', 'string'], ['error', 'string']]),
  valueObject('BoolResult', [['code', 'int'], ['value', 'bool'], ['error', 'string']]),
];

const CPP_ARGUMENT: Readonly<Record<string, string>> = {
  int: 'int',
  double: 'double',
  bool: 'bool',
  string: 'const std::string &',
};

const TS_ARGUMENT: Readonly<Record<string, string>> = {
  int: 'number',
  double: 'number',
  bool: 'boolean',
  string: 'string',
};

function lookup(table: Readonly<Record<string, string>>, key: string, what: string): string {
  const value = table[key];

  if (value === undefined) {
    throw new Error(`no ${what} for boundary type "${key}"`);
  }

  return value;
}

/** The C++ parameter type of an Embind boundary type. */
export function cppArgument(boundary: string): string {
  return lookup(CPP_ARGUMENT, boundary, 'C++ argument type');
}

/** The TypeScript type of an Embind boundary type. */
export function tsArgument(boundary: string): string {
  return lookup(TS_ARGUMENT, boundary, 'TypeScript type');
}

export function structSpec(binding: TypeBinding): ProjectionSpec {
  if (!binding.projection) {
    throw new Error('struct binding is missing its projection');
  }

  return binding.projection;
}

