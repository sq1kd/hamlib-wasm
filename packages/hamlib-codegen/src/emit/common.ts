/** One value a generated operation returns, as a field of its result. */
export interface ValueField {
  /** The result field, and the public name when the result is an object. */
  readonly name: string;
  readonly binding: TypeBinding;
  /** Length of a `char[N]` member, which is never null. */
  readonly charArray: number | null;
  /** The C expression holding the value once the call returned. */
  readonly source: string;
}

/** One JavaScript argument of a generated operation. */
export interface Parameter {
  /** The public parameter name, from the C parameter. */
  readonly name: string;
  /** The C++ parameter of the Embind function. */
  readonly local: string;
  readonly binding: TypeBinding;
}

/**
 * A struct projection the public surface hands out through a narrowing
 * module of its own instead of as the raw value object.
 *
 * `rig_ext_lookup`/`rig_ext_lookup_tok` return a `struct confparams *`, and
 * `tokenForeach` and the three `ext*Foreach` walkers return a vector of the
 * same projection; `src/native/confparams.ts` owns the narrowed public shape,
 * so the emitted methods project through it.  A second such projection grows
 * an entry here rather than a special case in the emitters.
 */
export interface PublicProjection {
  /** The public element type. */
  readonly element: string;
  /** Narrows one value object (or a result carrying its fields). */
  readonly project: string;
  /** Drains and frees a vector of them. */
  readonly collect: string;
}

const PUBLIC_PROJECTIONS: Readonly<Record<string, PublicProjection>> = {
  RigConfparams: { element: 'RigConfparam', project: 'projectConfparam', collect: 'collectConfparams' },
};

/** The public projection of a C++ projection type, if it has one. */
export function publicProjection(cpp: string): PublicProjection | undefined {
  return PUBLIC_PROJECTIONS[cpp];
}

export interface OperationFacts {
  readonly operation: GeneratedOperation;
  /** Whether the Embind function takes the rig handle first. */
  readonly needsHandle: boolean;
  /** The Embind value object the native call returns. */
  readonly result: string;
  /** The values that result carries besides `code` and `error`. */
  readonly fields: readonly ValueField[];
  /** Whether the public method resolves to the lone `value` field. */
  readonly unwrapsValue: boolean;
  readonly parameters: readonly Parameter[];
  /** The `rig_caps` member the operation is gated on, or `null`. */
  readonly gate: string | null;
  /** For a pure struct result handed out through a narrowing module. */
  readonly projection: PublicProjection | null;
}

/**
 * Operations whose frontend does not depend on the matching `rig_caps` member.
 * `rig_power2mW`/`rig_mW2power` call the backend's converter when it has one
 * and otherwise convert through the model's transmit ranges, so gating them on
 * the member would refuse every model that relies on the fallback.
 */
const FRONTEND_FALLBACK: ReadonlySet<string> = new Set(['rig_power2mW', 'rig_mW2power']);

/** Every shape's native locals: getter outputs, and the pure call's return. */
export const RETURNED = 'returned';
export const SOURCE = 'source';

export function outName(index: number): string {
  return `out${index}`;
}

/** Distinct, valid parameter names for the public interface. */
export function parameterNames(proposed: readonly string[]): string[] {
  const used = new Set<string>();

  return proposed.map((candidate, index) => {
    const base = /^[A-Za-z_][A-Za-z0-9_]*$/.test(candidate) ? candidate : `arg${index}`;
    let name = base;
    let suffix = 1;

    while (used.has(name)) {
      name = `${base}${suffix++}`;
    }

    used.add(name);
    return name;
  });
}

const RESERVED_FIELDS: ReadonlySet<string> = new Set(['code', 'error']);

function valueFields(operation: GeneratedOperation): ValueField[] {
  const fields: ValueField[] = [];

  if (operation.shape === 'pure') {
    const binding = operation.pure as TypeBinding;

    if (binding.category !== 'struct') {
      return [{ name: 'value', binding, charArray: null, source: RETURNED }];
    }

    for (const field of structSpec(binding).fields) {
      fields.push({ name: field.name, binding: field.binding, charArray: field.charArray, source: `${SOURCE}->${field.member}` });
    }
  }

  for (const [index, output] of operation.outputs.entries()) {
    if (output.binding.category === 'struct') {
      /* A struct output is flattened into one field per projected member, so
       * the result stays a flat value object (Embind does not nest value
       * objects reliably). */
      for (const field of structSpec(output.binding).fields) {
        fields.push({
          name: field.name,
          binding: field.binding,
          charArray: field.charArray,
          source: `${outName(index)}.${field.member}`,
        });
      }
    } else {
      fields.push({
        name: operation.outputs.length === 1 ? 'value' : output.field,
        binding: output.binding,
        charArray: null,
        source: outName(index),
      });
    }
  }

  for (const field of fields) {
    if (RESERVED_FIELDS.has(field.name)) {
      throw new Error(`${operation.symbol}: a result field may not be named ${field.name}`);
    }
  }

  return fields;
}

/** The `rig_caps` member that says whether a model implements the operation. */
function gateOf(operation: GeneratedOperation, capsMembers: ReadonlySet<string>): string | null {
  if (operation.shape === 'pure' || FRONTEND_FALLBACK.has(operation.symbol)) {
    return null;
  }

  const member = operation.symbol.startsWith('rig_') ? operation.symbol.slice(4) : operation.symbol;

  return capsMembers.has(member) ? member : null;
}

export function operationFacts(operation: GeneratedOperation, capsMembers: ReadonlySet<string>): OperationFacts {
  const fields = valueFields(operation);
  const names = parameterNames(operation.arguments.map((argument) => argument.field));
  const pure = operation.shape === 'pure' ? (operation.pure as TypeBinding) : null;

  return {
    operation,
    needsHandle: operation.plan.some((entry) => entry.kind === 'rig'),
    result: operation.result,
    fields,
    unwrapsValue: fields.length === 1 && fields[0]?.name === 'value',
    parameters: operation.arguments.map((argument, index) => ({
      name: names[index] as string,
      local: `arg${index}`,
      binding: argument.binding,
    })),
    gate: gateOf(operation, capsMembers),
    projection: pure?.category === 'struct' ? (publicProjection(structSpec(pure).cpp) ?? null) : null,
  };
}

