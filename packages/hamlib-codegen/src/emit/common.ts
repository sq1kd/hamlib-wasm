/** The projections a generated operation names a C++ type for. */
export function usedProjections(facts: readonly OperationFacts[]): ProjectionSpec[] {
  const specs = new Map<string, ProjectionSpec>();

  for (const { operation } of facts) {
    for (const binding of [...operation.arguments.map((argument) => argument.binding), operation.pure]) {
      if (binding?.category === 'struct') {
        const spec = structSpec(binding);
        specs.set(spec.cpp, spec);
      }
    }
  }

  return [...specs.values()].sort((a, b) => a.cpp.localeCompare(b.cpp));
}

/** The C++ type of a value object field. */
export function fieldCpp(boundary: string): string {
  return boundary === 'string' ? 'std::string' : boundary;
}

/** The generated value objects: the shared flat results and every per-operation one. */
export function resultObjects(model: Model, facts: readonly OperationFacts[]): ValueObject[] {
  const objects = new Map<string, ValueObject>();
  const used = new Set([...facts.map((fact) => fact.result), ...model.operations.map((operation) => operation.result)]);

  for (const flat of FLAT_RESULTS) {
    if (used.has(flat.name)) {
      objects.set(flat.name, flat);
    }
  }

  for (const fact of facts) {
    if (objects.has(fact.result) || fact.result in model.results) {
      continue;
    }

    objects.set(fact.result, {
      name: fact.result,
      fields: [
        { name: 'code', boundary: 'int' },
        ...fact.fields.map((field) => ({ name: field.name, boundary: field.binding.boundary })),
        { name: 'error', boundary: 'string' },
      ],
    });
  }

  return [...objects.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** The fields of a value object a bespoke operation returns. */
export function bespokeResultFields(model: Model, result: string): readonly ConfigPair[] {
  const declared = model.results[result]?.fields;

  if (declared) {
    return declared;
  }

  const flat = FLAT_RESULTS.find((candidate) => candidate.name === result);

  if (!flat) {
    throw new Error(`no value object ${result}`);
  }

  return flat.fields.map((field) => [field.name, field.boundary] as const);
}

/** The vector binding a `T[]` config result crosses as. */
export function vectorBinding(model: Model, result: string): string {
  const element = result.slice(0, -2);
  const vector = model.vectors.find((candidate) => candidate.type === element);

  if (!vector) {
    throw new Error(`${result} is not a registered vector (vectors: ${model.vectors.map((entry) => entry.type).join(', ')})`);
  }

  return vector.binding;
}

/** The rig-scoped config operations; each becomes a real method. */
export function bespokeOperations(model: Model): readonly ModelOperation[] {
  return model.operations.filter((operation) => operation.scope === 'rig');
}

