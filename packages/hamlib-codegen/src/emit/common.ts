/** The modules generated TypeScript imports types and helpers from. */
export type ImportModule = 'embind' | 'names' | 'confparams' | 'operations';

/**
 * The imports of one generated file, collected as the code that needs them
 * is emitted: every name is registered with the module it comes from, so the
 * import list follows the code without reading it back.
 */
export class Imports {
  readonly #types = new Map<ImportModule, Set<string>>();
  readonly #values = new Map<ImportModule, Set<string>>();

  type(module: ImportModule, name: string): string {
    this.#add(this.#types, module, name);
    return name;
  }

  value(module: ImportModule, name: string): string {
    this.#add(this.#values, module, name);
    return name;
  }

  /** A TypeScript type of the public surface, importing what it names. */
  ts(binding: TypeBinding): string {
    if (binding.category === 'struct') {
      return this.type('embind', structSpec(binding).cpp);
    }

    if (VOCABULARY_TYPES.has(binding.ts)) {
      return this.type('names', binding.ts);
    }

    if (binding.ts !== 'number' && binding.ts !== 'string' && binding.ts !== 'boolean') {
      throw new Error(`no module declares the TypeScript type ${binding.ts}`);
    }

    return binding.ts;
  }

  /** A narrowed config type (`PttState`), importing it. */
  narrowed(name: string): string {
    if (!VOCABULARY_TYPES.has(name)) {
      throw new Error(`${name} is not a generated vocabulary`);
    }

    return this.type('names', name);
  }

  #add(map: Map<ImportModule, Set<string>>, module: ImportModule, name: string): void {
    const names = map.get(module) ?? new Set<string>();
    names.add(name);
    map.set(module, names);
  }

  /** The import statements, given each module's path from the file. */
  render(paths: Readonly<Partial<Record<ImportModule, string>>>): string[] {
    const lines: string[] = [];
    const modules = [...new Set([...this.#values.keys(), ...this.#types.keys()])];

    for (const module of modules) {
      const from = paths[module];

      if (from === undefined) {
        throw new Error(`no import path for the ${module} module`);
      }

      const values = [...(this.#values.get(module) ?? [])].sort();
      const types = [...(this.#types.get(module) ?? [])].filter((name) => !values.includes(name)).sort();

      if (values.length > 0) {
        lines.push(`import { ${values.join(', ')} } from '${from}';`);
      }

      if (types.length > 0) {
        lines.push(`import type { ${types.join(', ')} } from '${from}';`);
      }
    }

    return lines;
  }
}
